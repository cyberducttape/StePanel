#!/usr/bin/env python3
"""Generate the small supported SDK catalogs and CLI completions from OpenAPI.

The generator intentionally reads only OpenAPI path/method/operationId and the
StePanel x-stepanel-cli extension; the full YAML remains the source of request
and response schemas for general OpenAPI tooling.
"""
import argparse
import difflib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs/openapi.yaml"


def parse_contract():
    operations = []
    path = None
    method = None
    current = None
    for line in SPEC.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^  (/[^:]+):\s*$", line)
        if match:
            path = match.group(1)
            method = None
            current = None
            continue
        match = re.match(r"^    (get|post|put|patch|delete|head|options):\s*$", line)
        if match and path:
            method = match.group(1).upper()
            current = {"path": path, "method": method, "id": "", "cli": ""}
            operations.append(current)
            continue
        if current:
            match = re.match(r"^      operationId:\s*([A-Za-z][A-Za-z0-9_]*)\s*$", line)
            if match:
                current["id"] = match.group(1)
            match = re.match(r"^      x-stepanel-cli:\s*([a-z][a-z-]*(?:\s+[a-z][a-z-]*)?)\s*$", line)
            if match:
                current["cli"] = match.group(1)
    operations = [op for op in operations if op["id"]]
    ids = [op["id"] for op in operations]
    if len(ids) != len(set(ids)):
        raise ValueError("OpenAPI operationId values must be unique")
    version_match = re.search(r"^  version:\s*([^\s]+)\s*$", SPEC.read_text(encoding="utf-8"), re.M)
    if not version_match:
        raise ValueError("OpenAPI info.version is required")
    return operations, version_match.group(1)


def outputs(operations, version):
    go_rows = "\n".join(
        f'\t{{ID: "{op["id"]}", Method: "{op["method"]}", Path: "{op["path"]}", CLICommand: "{op["cli"]}"}},'
        for op in operations
    )
    go = f'''// Code generated by scripts/generate-api-artifacts.py; DO NOT EDIT.
package stepanel

// ContractVersion is the OpenAPI info.version used to generate this client.
const ContractVersion = "{version}"

// Operation describes an operation in the checked-in OpenAPI contract.
type Operation struct{{ ID, Method, Path, CLICommand string }}

// contractOperations is generated from docs/openapi.yaml.
var contractOperations = [...]Operation{{
{go_rows}
}}

// ContractOperations returns a copy of generated operation metadata.
func ContractOperations() []Operation {{ return append([]Operation(nil), contractOperations[:]...) }}
'''
    ts_rows = ",\n".join(
        f'  {{ id: "{op["id"]}", method: "{op["method"]}", path: "{op["path"]}", cliCommand: "{op["cli"]}" }}'
        for op in operations
    )
    ts = f'''// Code generated by scripts/generate-api-artifacts.py; DO NOT EDIT.
export const contractVersion = "{version}";
export type ContractOperation = {{ id: string; method: string; path: string; cliCommand: string }};
export const contractOperations: readonly ContractOperation[] = [
{ts_rows}
];

export class StePanelClient {{
  constructor(private readonly baseURL: string, private readonly token: string, private readonly fetcher: typeof fetch = fetch) {{}}
  private url(path: string): URL {{
    const target = new URL(path, this.baseURL);
    const loopback = target.hostname === "localhost" || target.hostname === "127.0.0.1" || target.hostname === "[::1]";
    if (this.token && target.protocol !== "https:" && !loopback) throw new Error("Refusing to send bearer token over non-TLS HTTP");
    return target;
  }}
  async requestOperation<T>(operationId: string, body?: unknown, headers: Record<string, string> = {{}}): Promise<T> {{
    const operation = contractOperations.find((item) => item.id === operationId);
    if (!operation) throw new Error(`Unknown OpenAPI operation: ${{operationId}}`);
    return this.request<T>(operation.method, operation.path, body, headers);
  }}
  async request<T>(method: string, path: string, body?: unknown, headers: Record<string, string> = {{}}): Promise<T> {{
    const response = await this.fetcher(this.url(path), {{
      method, headers: {{ Accept: "application/json", ...(body === undefined ? {{}} : {{ "Content-Type": "application/json" }}), ...(this.token ? {{ Authorization: `Bearer ${{this.token}}` }} : {{}}), ...headers }},
      body: body === undefined ? undefined : JSON.stringify(body),
    }});
    if (!response.ok) throw new Error(`StePanel API ${{response.status}} (${{response.headers.get("X-Request-ID") || "no request id"}}): ${{(await response.text()).slice(0, 4096)}}`);
    return response.status === 204 ? undefined as T : response.json() as Promise<T>;
  }}
  async uploadOperation<T>(operationId: string, field: string, file: Blob, filename = "upload.bin"): Promise<T> {{
    const operation = contractOperations.find((item) => item.id === operationId);
    if (!operation || operation.method !== "POST") throw new Error(`Unknown upload POST operation: ${{operationId}}`);
    const form = new FormData(); form.append(field, file, filename);
    const response = await this.fetcher(this.url(operation.path), {{ method: operation.method, headers: {{ Accept: "application/json", ...(this.token ? {{ Authorization: `Bearer ${{this.token}}` }} : {{}}) }}, body: form }});
    if (!response.ok) throw new Error(`StePanel API ${{response.status}} (${{response.headers.get("X-Request-ID") || "no request id"}}): ${{(await response.text()).slice(0, 4096)}}`);
    return response.json() as Promise<T>;
  }}
}}
'''
    commands = sorted({op["cli"] for op in operations if op["cli"]})
    roots = sorted({command.split()[0] for command in commands} | {"status", "doctor", "capabilities", "completion", "provision"})
    bash_cases = []
    for root in roots:
        subs = sorted({c.split()[1] for c in commands if c.startswith(root + " ")})
        if subs:
            bash_cases.append(f'    {root}) COMPREPLY=( $(compgen -W "{" ".join(subs)}" -- "$cur") ) ;;')
    bash = '''# Generated from docs/openapi.yaml by scripts/generate-api-artifacts.py.
_stepanelctl_complete() {
  local cur prev
  cur="${COMP_WORDS[COMP_CWORD]}"; prev="${COMP_WORDS[COMP_CWORD-1]}"
  if (( COMP_CWORD == 1 )); then
    COMPREPLY=( $(compgen -W "''' + " ".join(roots) + '''" -- "$cur") )
    return
  fi
  case "${COMP_WORDS[1]}" in
''' + "\n".join(bash_cases) + '''
  esac
}
complete -F _stepanelctl_complete stepanelctl
'''
    zsh = "#compdef stepanelctl\n# Generated from docs/openapi.yaml by scripts/generate-api-artifacts.py.\n_arguments '1:command:((" + " ".join(roots) + "))' '*:argument:()'\n"
    fish_lines = ["# Generated from docs/openapi.yaml by scripts/generate-api-artifacts.py."]
    fish_lines += [f"complete -c stepanelctl -f -n '__fish_use_subcommand' -a '{root}'" for root in roots]
    for command in commands:
        words = command.split()
        if len(words) > 1:
            fish_lines.append(f"complete -c stepanelctl -f -n '__fish_seen_subcommand_from {words[0]}' -a '{words[1]}'")
    fish = "\n".join(fish_lines) + "\n"
    completion_go = '''// Code generated by scripts/generate-api-artifacts.py; DO NOT EDIT.
package main

var generatedCompletions = map[string]string{
'''
    max_name = max(len(name) for name in ("bash", "zsh", "fish"))
    for name, value in (("bash", bash), ("zsh", zsh), ("fish", fish)):
        completion_go += f'\t"{name}":{" " * (1 + max_name - len(name))}{json.dumps(value)},\n'
    completion_go += "}\n"
    return {
        ROOT / "sdk/go/stepanel/operations_gen.go": go,
        ROOT / "sdk/typescript/client.gen.ts": ts,
        ROOT / "completions/stepanelctl.bash": bash,
        ROOT / "completions/_stepanelctl": zsh,
        ROOT / "completions/stepanelctl.fish": fish,
        ROOT / "cmd/stepanelctl/completion_gen.go": completion_go,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    try:
        generated = outputs(*parse_contract())
    except (OSError, ValueError) as exc:
        print(exc, file=sys.stderr)
        return 1
    stale = False
    for target, content in generated.items():
        if args.check:
            existing = target.read_text(encoding="utf-8") if target.exists() else ""
            if existing != content:
                stale = True
                print(f"generated API artifact is stale: {target.relative_to(ROOT)}")
                print("".join(difflib.unified_diff(existing.splitlines(True), content.splitlines(True), fromfile="checked-in", tofile="generated")))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
