#!/usr/bin/env bash
set -Eeuo pipefail

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf -- "$tmp"' EXIT
mkdir -p "$tmp/bin"
cat >"$tmp/bin/chown" <<'SH'
#!/usr/bin/env bash
set -Eeuo pipefail
[[ $1 == root:root && $2 == -- && -f $3 && ! -L $3 ]]
printf 'chown:%s\n' "$3" >> "$CALL_LOG"
[[ ${FAIL_CHOWN:-0} != 1 ]]
SH
cat >"$tmp/bin/chmod" <<'SH'
#!/usr/bin/env bash
set -Eeuo pipefail
[[ $1 == 0600 && $2 == -- && -f $3 && ! -L $3 ]]
printf 'chmod:%s\n' "$3" >> "$CALL_LOG"
[[ ${FAIL_CHMOD:-0} != 1 ]]
SH
cat >"$tmp/bin/stat" <<'SH'
#!/usr/bin/env bash
set -Eeuo pipefail
[[ $1 == -c && $3 == -- && -f $4 && ! -L $4 ]]
case "$2" in
  %u) printf '%s\n' "${FILE_OWNER:-1000}" ;;
  %a) printf '%s\n' "${FILE_MODE:-600}" ;;
  %h) printf '%s\n' "${FILE_LINKS:-1}" ;;
  *) exit 2 ;;
esac
SH
chmod +x "$tmp/bin/chown" "$tmp/bin/chmod"
chmod +x "$tmp/bin/stat"

# Both a manually generated, user-owned file and a file generated by the
# privileged guided setup pass through the same promotion step.
source "$repo/deploy/lib/install-env-file.sh"
for origin in direct-setup guided-setup; do
  file="$tmp/$origin.env"
  printf 'STEPANEL_PANEL_HOSTNAME="example.test"\n' > "$file"
  (
    export CALL_LOG="$tmp/calls.log" SUDO_UID=1000 PATH="$tmp/bin:$PATH"
    secure_install_settings_file "$file"
  )
  [[ $(tail -n 2 "$tmp/calls.log") == "$(printf 'chown:%s\nchmod:%s' "$file" "$file")" ]]
done

# A symlink must be rejected before either privileged metadata operation.
ln -s "$tmp/direct-setup.env" "$tmp/linked.env"
: > "$tmp/symlink-calls.log"
if (
  export CALL_LOG="$tmp/symlink-calls.log" SUDO_UID=1000 PATH="$tmp/bin:$PATH"
  secure_install_settings_file "$tmp/linked.env"
) 2>/dev/null; then
  echo 'guided setup accepted a symlink settings file' >&2
  exit 1
fi
[[ ! -s "$tmp/symlink-calls.log" ]]

for invalid in owner mode links; do
  : > "$tmp/invalid-calls.log"
  args=(CALL_LOG="$tmp/invalid-calls.log" SUDO_UID=1000 PATH="$tmp/bin:$PATH")
  case "$invalid" in
    owner) args+=(FILE_OWNER=1001) ;;
    mode) args+=(FILE_MODE=640) ;;
    links) args+=(FILE_LINKS=2) ;;
  esac
  if (
    export "${args[@]}"
    secure_install_settings_file "$tmp/direct-setup.env"
  ) 2>/dev/null; then
    echo "guided setup accepted settings with invalid $invalid" >&2
    exit 1
  fi
  [[ ! -s "$tmp/invalid-calls.log" ]]
done

: > "$tmp/failure-calls.log"
if (
  export CALL_LOG="$tmp/failure-calls.log" SUDO_UID=1000 FAIL_CHOWN=1 PATH="$tmp/bin:$PATH"
  secure_install_settings_file "$tmp/direct-setup.env"
) 2>/dev/null; then
  echo 'guided setup hid a failed ownership change' >&2
  exit 1
fi
[[ $(<"$tmp/failure-calls.log") == "chown:$tmp/direct-setup.env" ]]

: > "$tmp/failure-calls.log"
if (
  export CALL_LOG="$tmp/failure-calls.log" SUDO_UID=1000 FAIL_CHMOD=1 PATH="$tmp/bin:$PATH"
  secure_install_settings_file "$tmp/direct-setup.env"
) 2>/dev/null; then
  echo 'guided setup hid a failed permissions change' >&2
  exit 1
fi
[[ $(<"$tmp/failure-calls.log") == "$(printf 'chown:%s\nchmod:%s' "$tmp/direct-setup.env" "$tmp/direct-setup.env")" ]]

# Keep the promotion outside the branch that generates new answers, so reuse
# and freshly generated settings both receive the same treatment.
reuse_line=$(grep -n 'if \[\[ \$reuse_answers != y \]\]' "$repo/install.sh" | head -1 | cut -d: -f1)
config_branch_line=$(grep -n 'if \[\[ -n \$CONFIG_FILE \]\]; then' "$repo/install.sh" | head -1 | cut -d: -f1)
secure_line=$(grep -n 'secure_install_settings_file "\$CONFIG_FILE"' "$repo/install.sh" | head -1 | cut -d: -f1)
load_line=$(grep -n 'load_env_file "\$CONFIG_FILE" private' "$repo/install.sh" | head -1 | cut -d: -f1)
[[ -n $reuse_line && -n $config_branch_line && -n $secure_line && -n $load_line && \
  $reuse_line -lt $config_branch_line && $config_branch_line -lt $secure_line &&
  $secure_line -lt $load_line ]] || {
  echo 'every installer settings file must be secured before loading it' >&2
  exit 1
}

echo 'guided installer saved-settings ownership contract passed'
